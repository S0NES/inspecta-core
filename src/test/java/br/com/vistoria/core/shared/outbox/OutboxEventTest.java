package br.com.vistoria.core.shared.outbox;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

@DisplayName("OutboxEvent")
class OutboxEventTest {

    @Test
    @DisplayName("of() creates event with routing key and payload")
    void of_createsEvent() {
        String routingKey = "test.event";
        String payload = "{\"key\":\"value\"}";

        OutboxEvent event = OutboxEvent.of(routingKey, payload);

        assertThat(event.getRoutingKey()).isEqualTo(routingKey);
        assertThat(event.getPayload()).isEqualTo(payload);
        assertThat(event.getId()).isNull(); // Will be generated by DB
        assertThat(event.getTentativas()).isZero();
        assertThat(event.getPublicadoEm()).isNull();
        assertThat(event.getCriadoEm()).isNotNull();
    }

    @Test
    @DisplayName("default tentativas is 0")
    void defaultTentativas() {
        OutboxEvent event = new OutboxEvent();
        assertThat(event.getTentativas()).isEqualTo(0);
    }

    @Test
    @DisplayName("payload defaults to null")
    void payloadDefaultsToNull() {
        OutboxEvent event = new OutboxEvent();
        assertThat(event.getPayload()).isNull();
    }

    @Test
    @DisplayName("criadoEm is set on instantiation")
    void criadoEmIsSet() {
        OutboxEvent event = new OutboxEvent();
        assertThat(event.getCriadoEm()).isNotNull();
    }
}
